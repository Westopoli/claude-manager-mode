#!/usr/bin/env python3
"""Phase 3.5.1 — degenerate-fake sweep. Invoked by /manager-mode after the test audit.

Why this exists
---------------
The Phase 3.4 audit judges tests by reading them. Nothing before leaf spawn
proves a test goes red against wrong code. This script replaces each leaf's
impl file, in a scratch worktree, with a degenerate fake that returns nothing /
0 / its first argument / True for every symbol the tests import, then runs the
leaf's tests. A test that still PASSES against a fake that does no work asserts
nothing a real bug could break.

Exit codes: 0 clean, 1 findings, 2 config/resolution error.
The fakes carry no signature knowledge and never read the spec; they are
mechanical on purpose. Writes DEGENERATE-SWEEP.md/.json under
`.swarm/<slug>/audits/wave-N/<shard>/` and prints the markdown verbatim.
"""
from __future__ import annotations

import argparse
import ast
import json
import subprocess
import sys
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
sys.path.insert(0, str(SCRIPT_DIR))
import check_invariants as ci  # noqa: E402
import test_results as tr  # noqa: E402
import worktree_ops as wo  # noqa: E402

RETURN_EXPR = {
    "none": "None",
    "const": "0",
    "identity": "(a[0] if a else None)",
    "true": "True",
}


def stub_source(symbols: dict[str, str], variant: str) -> str:
    """Fake module source. `symbols` maps name -> "class" | "callable"."""
    expr = RETURN_EXPR[variant]
    lines = [
        "# degenerate fake — generated by degenerate_sweep.py",
        f"def _stub(*a, **k):\n    return {expr}\n",
        "def __getattr__(name):\n"
        "    if name.startswith('__'):\n"
        "        raise AttributeError(name)\n"
        "    return _stub\n",
    ]
    for name, kind in sorted(symbols.items()):
        if kind == "class":
            lines.append(
                f"class {name}:\n"
                f"    def __init__(self, *a, **k):\n        pass\n"
                f"    def __getattr__(self, n):\n"
                f"        if n.startswith('__'):\n            raise AttributeError(n)\n"
                f"        return _stub\n"
                f"    def __call__(self, *a, **k):\n        return {expr}\n")
        else:
            lines.append(f"def {name}(*a, **k):\n    return {expr}\n")
    return "\n".join(lines)


def _mod_key(path_or_mod: str) -> str:
    m = path_or_mod[:-3] if path_or_mod.endswith(".py") else path_or_mod
    m = m.replace("/", ".").strip(".")
    return m[4:] if m.startswith("src.") else m


def _imports_from(test_src: str, impl_rel: str) -> set[str]:
    """Names the test imports from the module at `impl_rel`."""
    try:
        tree = ast.parse(test_src)
    except SyntaxError:
        return set()
    want = _mod_key(impl_rel)
    out: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and node.module:
            got = _mod_key(node.module)
            if got == want or want.endswith("." + got) or got.endswith("." + want):
                out.update(a.name for a in node.names if a.name != "*")
    return out


def _contract_kinds(root: Path, contract_path: str) -> dict[str, str]:
    p = root / contract_path if contract_path else None
    if not p or not p.is_file() or p.suffix != ".py":
        return {}
    try:
        tree = ast.parse(p.read_text())
    except SyntaxError:
        return {}
    return {n.name: ("class" if isinstance(n, ast.ClassDef) else "callable")
            for n in tree.body if isinstance(n, (ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef))}


def leaf_symbols(root: Path, cfg: dict, b: ci.Brief, impl_rel: str) -> dict[str, str]:
    kinds = _contract_kinds(root, cfg.get("type_contract_path", ""))
    names = {s for s in (b.frontmatter.get("contract_imports") or []) if isinstance(s, str)}
    for t in ci._leaf_paths(b, "test"):
        tp = root / t
        if tp.suffix == ".py" and tp.is_file():
            names |= _imports_from(tp.read_text(), impl_rel)
    return {n: kinds.get(n, "callable") for n in names if n.isidentifier()}


def test_command(b: ci.Brief, override: str | None) -> str:
    if override:
        return override
    cmd = wo.acceptance_cmd(b)
    if cmd:
        return cmd
    return "python3 -m pytest " + " ".join(ci._leaf_paths(b, "test"))


def sweep_leaf(root: Path, cfg: dict, b: ci.Brief, scratch: Path, test_cmd: str | None,
               timeout: int, variants: list[str]) -> dict:
    impls = ci._leaf_paths(b, "impl")
    res: dict = {"leaf": b.leaf_id, "tests": {}, "advisory": [], "findings": [], "collected": {}}
    py_impls = [i for i in impls if i.endswith(".py")]
    if not py_impls:
        res["advisory"].append("unsupported language, skipped")
        return res
    cmd = test_command(b, test_cmd)
    for variant in variants:
        saved: dict[Path, str | None] = {}
        for rel in py_impls:
            dst = scratch / rel
            saved[dst] = dst.read_text() if dst.is_file() else None
            dst.parent.mkdir(parents=True, exist_ok=True)
            dst.write_text(stub_source(leaf_symbols(root, cfg, b, rel), variant))
        try:
            run = tr.run_tests(cmd, scratch, timeout=timeout)
        finally:
            for dst, old in saved.items():
                if old is None:
                    dst.unlink(missing_ok=True)
                else:
                    dst.write_text(old)
        res["collected"][variant] = run.collected
        for tid, state in run.states.items():
            res["tests"].setdefault(tid, {})[variant] = state
    for tid, per in sorted(res["tests"].items()):
        passed = [v for v, s in per.items() if s == "PASS"]
        if passed:
            res["findings"].append(
                f"🔴 `{tid}` PASSES against a degenerate fake ({', '.join(passed)}) — "
                f"asserts nothing a wrong implementation could break")
    if variants and not any(res["collected"].values()):
        res["findings"].append(
            f"🔴 no test collected under any fake (`{cmd}`) — runner missing or tests import "
            f"something the sweep cannot stub")
    elif not all(res["collected"].values()):
        bad = [v for v, ok in res["collected"].items() if not ok]
        res["advisory"].append(f"collection failed under variant(s): {', '.join(bad)}")
    return res


def render(slug: str, wave: int, shard: str, results: list[dict], variants: list[str]) -> str:
    lines = [f"# Degenerate-fake sweep — wave {wave}, shard {shard or 'default'}", "",
             "| leaf | test | " + " | ".join(variants) + " | verdict |",
             "|------|------|" + "|".join("---" for _ in variants) + "|---------|"]
    for r in results:
        for tid, per in sorted(r["tests"].items()):
            bad = any(s == "PASS" for s in per.values())
            lines.append(f"| {r['leaf']} | `{tid}` | "
                         + " | ".join(per.get(v, "-") for v in variants)
                         + f" | {'🔴 vacuous' if bad else 'ok'} |")
    lines.append("")
    for r in results:
        for a in r["advisory"]:
            lines.append(f"- {r['leaf']}: advisory — {a}")
        for f in r["findings"]:
            if not f.startswith("🔴 `"):
                lines.append(f"- {r['leaf']}: {f}")
    n = sum(len(r["findings"]) for r in results)
    lines += ["", f"{n} finding(s)" if n else "clean"]
    return "\n".join(lines) + "\n"


def _scratch_cmd(root: Path, slug: str, action: str, name: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, str(SCRIPT_DIR / "worktree_ops.py"), "--root", str(root),
         "scratch", action, "--slug", slug, "--name", name],
        capture_output=True, text=True)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("--cascade", help="cascade slug (.swarm/<slug>/)")
    p.add_argument("--wave", type=int)
    p.add_argument("--shard")
    p.add_argument("--leaf", action="append", default=[])
    p.add_argument("--root", type=Path, default=Path.cwd())
    p.add_argument("--briefs-dir", type=Path)
    p.add_argument("--scratch-dir", type=Path, help="use this checkout instead of creating a scratch worktree")
    p.add_argument("--keep", action="store_true", help="leave the scratch worktree in place")
    p.add_argument("--test-cmd")
    p.add_argument("--timeout", type=int)
    args = p.parse_args(argv)

    root = wo.main_root(args.root.resolve())
    cfg = ci.load_config(root)
    slug = ci.discover_cascade_slug(root, args.cascade)
    if not slug:
        print("cannot resolve cascade slug — pass --cascade", file=sys.stderr)
        return 2
    bdir = ci.resolve_briefs_dir(root, cfg, args.briefs_dir, slug)
    ctx = wo.Ctx(root=root, slug=slug, cfg=cfg)
    briefs = wo.load_briefs(ctx) if not args.briefs_dir else {
        b.leaf_id: b for b in (ci.parse_brief(q) for q in sorted(bdir.glob("leaf-*.md"))
                               + sorted(bdir.glob("shard-*/leaf-*.md")) if "." not in q.stem) if b}
    chosen = [b for b in briefs.values()
              if (not args.leaf or b.leaf_id in args.leaf)
              and (args.wave is None or ci._wave(b) == args.wave)
              and (args.shard is None or ci._shard(b) == args.shard)]
    if not chosen:
        print("no briefs match the selection", file=sys.stderr)
        return 2
    sab = cfg["sabotage"]
    timeout = args.timeout or int(sab["timeout_seconds"])
    variants = [v for v in sab["variants"] if v in RETURN_EXPR]

    groups: dict[tuple[int, str], list[ci.Brief]] = {}
    for b in chosen:
        groups.setdefault((ci._wave(b), ci._shard(b)), []).append(b)

    total = 0
    for (wave, shard), members in sorted(groups.items()):
        name = f"sabotage-{shard or 'default'}"
        created = False
        scratch = args.scratch_dir
        if scratch is None:
            proc = _scratch_cmd(root, slug, "add", name)
            if proc.returncode != 0:
                print(proc.stderr.strip() or proc.stdout.strip(), file=sys.stderr)
                return 2
            scratch, created = ctx.scratch_dir(name), True
        try:
            results = [sweep_leaf(root, cfg, b, scratch, args.test_cmd, timeout, variants)
                       for b in members]
        finally:
            if created and not args.keep:
                _scratch_cmd(root, slug, "remove", name)
        text = render(slug, wave, shard, results, variants)
        out = root / ".swarm" / slug / "audits" / f"wave-{wave}" / (shard or "default")
        out.mkdir(parents=True, exist_ok=True)
        (out / "DEGENERATE-SWEEP.md").write_text(text)
        (out / "DEGENERATE-SWEEP.json").write_text(json.dumps(results, indent=1) + "\n")
        print(text)
        total += sum(len(r["findings"]) for r in results)
    return 1 if total else 0


if __name__ == "__main__":
    raise SystemExit(main())
